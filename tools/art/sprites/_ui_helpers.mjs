// ── Drawing helpers ─────────────────────────────────────────────────────────────────
// Scanline polygon fill, pixel-centre sampled. pts = [[x,y],...] in pixel-edge coordinates.
export function poly(p, pts, c) {
  const ys = pts.map((q) => q[1]);
  for (let y = Math.floor(Math.min(...ys)); y <= Math.ceil(Math.max(...ys)); y++) {
    const cy = y + 0.5, xs = [];
    for (let i = 0; i < pts.length; i++) {
      const [x0, y0] = pts[i], [x1, y1] = pts[(i + 1) % pts.length];
      if ((y0 <= cy && y1 > cy) || (y1 <= cy && y0 > cy)) xs.push(x0 + ((cy - y0) * (x1 - x0)) / (y1 - y0));
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2)
      for (let x = Math.ceil(xs[k] - 0.5); x <= Math.floor(xs[k + 1] - 0.5); x++) p.set(x, y, c);
  }
  return p;
}
// Thick line: a quad around the segment (x0,y0)-(x1,y1) in pixel-centre coords, half-width hw.
export function thick(p, x0, y0, x1, y1, hw, c) {
  const dx = x1 - x0, dy = y1 - y0, L = Math.hypot(dx, dy) || 1, nx = (-dy / L) * hw, ny = (dx / L) * hw;
  const ex = (dx / L) * 0.5, ey = (dy / L) * 0.5; // extend half a pixel at the caps
  const a = [x0 + 0.5 - ex, y0 + 0.5 - ey], b = [x1 + 0.5 + ex, y1 + 0.5 + ey];
  return poly(p, [[a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny], [b[0] - nx, b[1] - ny], [a[0] - nx, a[1] - ny]], c);
}
// Ring (annulus) between radii r0..r1 around (cx,cy), optionally limited to an angle range (radians, y down).
export function ring(p, cx, cy, r0, r1, c, a0 = -Infinity, a1 = Infinity) {
  for (let y = Math.floor(cy - r1 - 1); y <= Math.ceil(cy + r1 + 1); y++)
    for (let x = Math.floor(cx - r1 - 1); x <= Math.ceil(cx + r1 + 1); x++) {
      const dx = x + 0.5 - cx, dy = y + 0.5 - cy, d = Math.hypot(dx, dy);
      if (d < r0 || d > r1) continue;
      if (a0 !== -Infinity) { let a = Math.atan2(dy, dx); while (a < a0) a += Math.PI * 2; if (a > a1) continue; }
      p.set(x, y, c);
    }
  return p;
}
export function disc(p, cx, cy, r, c) { return ring(p, cx, cy, 0, r, c); }
// Hand-typed grid stamped at (ox,oy); '.' leaves the destination untouched.
export function put(p, rows, ox = 0, oy = 0) { return p.stamp(Px.grid(rows), ox, oy); }
// Replace only on pixels within a predicate.
export function recolor(p, fn) { for (let y = 0; y < p.h; y++) for (let x = 0; x < p.w; x++) { const c = fn(x, y, p.d[y][x]); if (c) p.d[y][x] = c; } return p; }
// Centre a grid inside a canvas of w×h (outline margin preserved), returns new Px.
export function centred(rows, w = 16, h = 16) {
  const g = Px.grid(rows), p = new Px(w, h);
  return p.stamp(g, Math.floor((w - g.w) / 2), Math.floor((h - g.h) / 2));
}

// Ring panel: a rounded rectangle built from concentric 1px rings. rings[i] is the colour of inset i:
// either a char or { t, l, b, r } per side (top/left lit, bottom/right shadowed). `fill` = everything deeper.
// `radius` cuts the outer corners (0 = square, 1 = notch, 2/3 = round).
export function ringPanel(w, h, rings, fill, radius = 2, opts = {}) {
  const p = new Px(w, h); const { squareBottom = false } = opts;
  const cut = { 0: 0, 1: 1, 2: 2, 3: 3 }[radius] ?? radius;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const dl = x, dr = w - 1 - x, dt = y, db = squareBottom ? 99 : h - 1 - y;
    let d = Math.min(dl, dr, dt, db);
    // rounded corners: chamfer by Manhattan distance into the corner square
    const cx = Math.min(dl, dr), cy = Math.min(dt, db);
    if (cut && cx < cut && cy < cut) { const m = cx + cy - (cut - 1); if (m < 0) continue; d = Math.min(d, m); }
    let c = d < rings.length ? rings[d] : fill;
    if (c && typeof c === 'object') {
      // which side is this pixel closest to? ties resolved top/left first (light wins on corners)
      const side = [['t', dt], ['l', dl], ['b', db], ['r', dr]].sort((a, b) => a[1] - b[1])[0][0];
      // corner pixels on the top-right / bottom-left diagonals get the base tone if given
      c = c[side] ?? c.m;
    }
    if (c && c !== '.') p.set(x, y, c);
  }
  return p;
}

